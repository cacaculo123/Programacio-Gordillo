x = int(input("Pon un numero\n"))
y = int(input("Pon otro numro\n"))

#Suma
print("Suma:", x + y)

#Resta
print("Resta:", x - y)
print("Resta:", y - x)

#Multiplicacion
print("Multiplicacion:", x * y)

#Division
print("Division:", x / y)
print("Division:", y / x)

#Division entera
print("Division entera:", x // y)
print("Division entera:", y // x)

#Potencia
print("Potencia:", x ** y)

#Porcentaje
print("Porcentaje:", x % y)



